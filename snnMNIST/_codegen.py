import shutil
from pathlib import Path

import nir as _nir
from snn_mlir._graph import parse_graph, quantize_layers
from snn_mlir.nodes import NodeInfo


def export(
    source: _nir.NIRGraph | str | Path,
    output_dir: str | Path,
    *,
    quantize: bool = False,
    n_steps: int = 100,
    index_bits: int = 32,
    input_file: str | Path | None = None,
) -> None:
    """Generate C runtime files (snn_data.h + main.c) for a NIR graph.

    Weights are baked into network.mlir as constant globals, so there is no
    snn_data.c — the header only carries layer-size macros.

    Intended to be called alongside snn_mlir.export() in example scripts.
    Not part of the pip-installable snn-mlir package.
    """
    if isinstance(source, (str, Path)):
        source = _nir.read(str(source))

    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)

    layers = parse_graph(source)
    if quantize:
        quantize_layers(layers)

    first_synapse = next(layer for layer in layers if layer.is_synapse)
    last_neuron = next(layer for layer in reversed(layers) if layer.is_neuron)

    generate_snn_header(
        layers,
        input_size=first_synapse.weight_shape[1],
        output_size=last_neuron.state_size,
        n_steps=n_steps,
        output_path=output_path,
    )
    generate_main_c(
        layers,
        input_size=first_synapse.weight_shape[1],
        output_size=last_neuron.state_size,
        n_steps=n_steps,
        output_path=output_path,
        quantize=quantize,
        index_bits=index_bits,
    )

    if input_file is not None:
        shutil.copy2(input_file, output_path / "input.h")


def generate_snn_header(
    layers: list[NodeInfo],
    input_size: int,
    output_size: int,
    n_steps: int,
    output_path: Path,
) -> None:
    """Write snn_data.h — layer-size macros only (weights live in network.mlir)."""
    _write_header(layers, input_size, output_size, n_steps, output_path)


def generate_main_c(
    layers: list[NodeInfo],
    input_size: int,
    output_size: int,
    n_steps: int,
    output_path: Path,
    quantize: bool,
    index_bits: int = 32,
) -> None:
    """Write main.c test harness (timestep loop, memref descriptors)."""
    idx_t = f"int{index_bits}_t"
    L: list[str] = []

    L.append("/* Auto-generated by snn-mlir — do NOT edit */")
    L.append("#include <stdio.h>")
    L.append("#include <stdint.h>")
    L.append('#include "snn_data.h"')
    L.append('#include "input.h"')
    L.append('#include "gem5_profile.h"')
    L.append("#ifndef HOST_SIM")
    L.append('#include "defines.h"')
    L.append("#endif")
    L.append("#ifndef NUM_TEST_VECTORS")
    L.append("#define NUM_TEST_VECTORS 1")
    L.append("#endif")

    L.append("")

    # ── memref descriptor typedefs ────────────────────────────────────────────
    L.append(f"/* MLIR memref descriptors ({index_bits}-bit index) */")
    if quantize:
        L += _memref_typedef("Memref1Di8", "int8_t", 1, idx_t)
        L += _memref_typedef("Memref1Di32", "int32_t", 1, idx_t)
    else:
        L += _memref_typedef("Memref1Df32", "float", 1, idx_t)
    L.append("")

    # ── extern function declaration ───────────────────────────────────────────
    L += _extern_signature(layers, idx_t, quantize)
    L.append("")

    # ── helper constructors ───────────────────────────────────────────────────
    L += _mk_helpers(idx_t, quantize)
    L.append("")

    # ── main ──────────────────────────────────────────────────────────────────
    L.append("int main(void) {")
    #L.append("uart_init();")

    last_neuron = next((layer for layer in reversed(layers) if layer.is_neuron), None)
    if quantize:
        if last_neuron and last_neuron.output_element_type(quantize) == "i32":
            out_t, out_desc_t, out_mk = "int32_t", "Memref1Di32", "mk1d_i32"
        else:
            out_t, out_desc_t, out_mk = "int8_t", "Memref1Di8", "mk1d_i8"
    else:
        out_t, out_desc_t, out_mk = "float", "Memref1Df32", "mk1d_f32"

    first_neuron = next((layer for layer in layers if layer.is_neuron), None)
    first_state_expr = None
    if first_neuron and first_neuron.state_names:
        first_state_expr = f"{first_neuron.state_names[0]}_{first_neuron.name}[0]"

    if not quantize:
        L.append("    float input_buf[INPUT_SIZE];")
    L.append(f"    {out_t} output_buf[OUTPUT_SIZE];")
    L.append("    int32_t output_spike_count[OUTPUT_SIZE] = {0};")
    L.append(f"    int32_t output_spike_train[{n_steps}] = {{0}};")
    L.append("    int32_t first_spike_step = -1;")
    L.append("")

    # state arrays
    s_t = "int32_t" if quantize else "float"
    for layer in layers:
        if layer.is_neuron:
            for sname in layer.state_names:
                L.append(
                    f"    {s_t} {sname}_{layer.name}[{layer.state_size_define}] = {{0}};",
                )
    L.append("")

    # static descriptors
    if not quantize:
        L.append("    Memref1Df32 in_desc = mk1d_f32(input_buf, INPUT_SIZE);")
    L.append(f"    {out_desc_t} out_desc = {out_mk}(output_buf, OUTPUT_SIZE);")

    # Weights are baked into network.mlir as constant globals — no descriptors here.

    # state descriptors
    s_desc_t = "Memref1Di32" if quantize else "Memref1Df32"
    s_mk = "mk1d_i32" if quantize else "mk1d_f32"
    for layer in layers:
        if layer.is_neuron:
            for sname in layer.state_names:
                L.append(
                    f"    {s_desc_t} {sname[0]}{layer.name}_desc"
                    f" = {s_mk}({sname}_{layer.name}, {layer.state_size_define});",
                )
    L.append("")

    L.append("    for (int vec = 0; vec < NUM_TEST_VECTORS; vec++) {")
    L.append("        for (int i = 0; i < OUTPUT_SIZE; i++) output_spike_count[i] = 0;")
    L.append(f"        for (int t = 0; t < {n_steps}; t++) output_spike_train[t] = 0;")
    L.append("        first_spike_step = -1;")
    for layer in layers:
        if layer.is_neuron:
            for sname in layer.state_names:
                L.append(
                    f"        for (int i = 0; i < {layer.state_size_define}; i++) {sname}_{layer.name}[i] = 0;",
                )
    L.append("")
    L.append("        snn_gem5_roi_begin((uint64_t)vec);")
    L.append("#ifdef SNN_PHASE_PROFILE")
    L.append("        extern void snn_phase_reset(void);")
    L.append("        snn_phase_reset();")
    L.append("#endif")
    L.append("")

    # timestep loop
    L.append(f"        for (int step = 0; step < {n_steps}; step++) {{")
    if quantize:
        L.append("            Memref1Di8 in_desc = mk1d_i8((int8_t *)L0_input[vec][step], INPUT_SIZE);")
    else:
        L.append("            for (int i = 0; i < INPUT_SIZE; i++)")
        L.append("                input_buf[i] = (float)L0_input[vec][step][i];")

    # build call args
    call_args = ["&in_desc"]
    for layer in layers:
        if layer.is_neuron:
            for sname in layer.state_names:
                call_args.append(f"&{sname[0]}{layer.name}_desc")
    call_args.append("&out_desc")

    L.append("            _mlir_ciface_snn_forward_step(")
    L.append("                " + ", ".join(call_args) + ");")
    L.append("")

    L.append("            int32_t spike_now = 0;")
    L.append("            for (int i = 0; i < OUTPUT_SIZE; i++) {")
    L.append("                if (output_buf[i] != 0) spike_now = 1;")
    L.append("            }")
    L.append("            output_spike_train[step] = spike_now;")
    L.append("            if (spike_now && first_spike_step < 0) first_spike_step = step;")
    L.append("")
    L.append("            for (int i = 0; i < OUTPUT_SIZE; i++) {")
    L.append("                output_spike_count[i] += (output_buf[i] != 0) ? 1 : 0;")
    L.append("            }")

    L.append("        }")
    L.append("        snn_gem5_roi_end((uint64_t)vec);")
    L.append("")

    L.append('        printf("\\nSpike counts per class: [");')
    L.append("        for (int i = 0; i < OUTPUT_SIZE; i++) {")
    L.append('            if (i > 0) printf(", ");')
    L.append('            printf("%d", (int)output_spike_count[i]);')
    L.append("        }")
    L.append('        printf("]\\n");')
    L.append("        int predicted_class = 0;")
    L.append("        for (int i = 1; i < OUTPUT_SIZE; i++) {")
    L.append("            if (output_spike_count[i] > output_spike_count[predicted_class])")
    L.append("                predicted_class = i;")
    L.append("        }")
    L.append('        printf("FINAL_CLASS[%d] %d\\n", vec, predicted_class);')
    L.append("#ifdef SNN_PHASE_PROFILE")
    L.append("        extern volatile uint64_t snn_phase_cycles[];")
    L.append(
        '        printf("PHASE_CYCLES vec=%d scan=%llu gather=%llu lif1=%llu fc2=%llu other=%llu\\n",'
    )
    L.append(
        "            vec,"
        " (unsigned long long)snn_phase_cycles[0],"
        " (unsigned long long)snn_phase_cycles[1],"
        " (unsigned long long)snn_phase_cycles[2],"
        " (unsigned long long)snn_phase_cycles[3],"
        " (unsigned long long)snn_phase_cycles[4]);"
    )
    L.append("#endif")
    L.append("    }")
    L.append("    return 0;")
    L.append("}")

    (output_path / "main.c").write_text("\n".join(L) + "\n")


# ── private helpers ────────────────────────────────────────────────────────────


def _memref_typedef(name: str, elem_t: str, rank: int, idx_t: str) -> list[str]:
    return [
        "typedef struct {",
        f"    {elem_t} *allocated;",
        f"    {elem_t} *aligned;",
        f"    {idx_t} offset;",
        f"    {idx_t} sizes[{rank}];",
        f"    {idx_t} strides[{rank}];",
        f"}} {name};",
    ]


def _extern_signature(layers: list[NodeInfo], idx_t: str, quantize: bool) -> list[str]:
    last_neuron = next((layer for layer in reversed(layers) if layer.is_neuron), None)
    if quantize:
        in_t, s_t = "Memref1Di8", "Memref1Di32"
        out_t = (
            "Memref1Di32"
            if (last_neuron and last_neuron.output_element_type(True) == "i32")
            else "Memref1Di8"
        )
    else:
        in_t, s_t = "Memref1Df32", "Memref1Df32"
        out_t = "Memref1Df32"

    # Weights are constant globals inside the module, not function arguments.
    args = [f"{in_t} *input"]
    for layer in layers:
        if layer.is_neuron:
            for sname in layer.state_names:
                args.append(f"{s_t} *{sname}_{layer.name}")
    args.append(f"{out_t} *output")

    return [
        "extern void _mlir_ciface_snn_forward_step(",
        "    " + ",\n    ".join(args),
        ");",
    ]


def _mk_helpers(idx_t: str, quantize: bool) -> list[str]:
    if quantize:
        return [
            f"static Memref1Di8 mk1d_i8(int8_t *p, {idx_t} n) {{",
            "    return (Memref1Di8){p, p, 0, {n}, {1}};",
            "}",
            f"static Memref1Di32 mk1d_i32(int32_t *p, {idx_t} n) {{",
            "    return (Memref1Di32){p, p, 0, {n}, {1}};",
            "}",
        ]
    return [
        f"static Memref1Df32 mk1d_f32(float *p, {idx_t} n) {{",
        "    return (Memref1Df32){p, p, 0, {n}, {1}};",
        "}",
    ]


def _write_header(
    layers: list[NodeInfo],
    input_size: int,
    output_size: int,
    n_steps: int,
    output_path: Path,
) -> None:
    lines = [
        "/* Auto-generated by snn-mlir — do NOT edit */",
        "#ifndef SNN_DATA_H",
        "#define SNN_DATA_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define N_STEPS      {n_steps}",
        f"#define INPUT_SIZE   {input_size}",
        f"#define INPUT_GRID_W {int(round((input_size // 2) ** 0.5))}",
        "#define INPUT_PLANE_SIZE (INPUT_GRID_W * INPUT_GRID_W)",
        f"#define OUTPUT_SIZE  {output_size}",
        "",
    ]
    for layer in layers:
        if layer.is_neuron:
            lines.append(f"#define {layer.state_size_define} {layer.state_size}")
    lines += [
        "",
        "/* Weights live as constant globals inside network.mlir, not here. */",
        "",
        "#endif /* SNN_DATA_H */",
    ]
    (output_path / "snn_data.h").write_text("\n".join(lines) + "\n")
