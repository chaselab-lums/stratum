#!/usr/bin/env python3
"""Write the one gem5 SNN report: baseline analysis and the L2 sweep."""

from __future__ import annotations

import html
import sys
from pathlib import Path

from gem5_bottleneck_html import build_html, parse_config, parse_stats
from gem5_sweep_report import assemble


def esc(value: object) -> str:
    return html.escape(str(value), quote=True)


def document_parts(text: str) -> tuple[str, str]:
    styles = []
    lower = text.lower()
    cursor = 0
    while True:
        start = lower.find("<style", cursor)
        if start == -1:
            break
        open_end = lower.find(">", start)
        close = lower.find("</style>", open_end)
        if open_end == -1 or close == -1:
            break
        styles.append(text[open_end + 1 : close])
        cursor = close + len("</style>")
    body_start = lower.find("<body>")
    body_end = lower.rfind("</body>")
    if body_start == -1 or body_end == -1:
        return "".join(styles), f"<pre>{esc(text)}</pre>"
    return "".join(styles), text[body_start + len("<body>") : body_end]


def profile_index(profile_root: Path) -> Path | None:
    for parent in [profile_root, *profile_root.parents]:
        candidate = parent / "profile.json"
        if candidate.exists():
            return candidate
    return None


def build(profile_root: Path) -> str:
    stats_dir = profile_root / "stats" / "inference-stats"
    extra_css = []
    stats_path = stats_dir / "stats.txt"
    if stats_path.exists():
        css, analysis = document_parts(
            build_html(stats_dir, parse_stats(stats_path), parse_config(stats_dir / "config.ini"))
        )
        extra_css.append(css)
    else:
        analysis = "<p>No stats session yet. Run <code>./profile.sh stats</code>.</p>"

    sweep_page, spike_note, _spike_ok = assemble(profile_root / "sweep", profile_index(profile_root))
    if sweep_page:
        css, sweep = document_parts(sweep_page)
        extra_css.append(css)
    else:
        sweep = f"<p>{esc(spike_note)}</p>"

    sections = [
        ("analysis", "Analysis", analysis),
        ("sweep", "L2 size", sweep),
    ]

    nav = "".join(f"<a href='#{anchor}'>{esc(title)}</a>" for anchor, title, _ in sections)
    body = "".join(
        f"<section id='{anchor}'><h2 class='part'>{esc(title)}</h2>{content}</section>"
        for anchor, title, content in sections
    )
    page = f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>SNN MNIST gem5 report</title>
  <style>
    :root {{ color-scheme: light; }}
    body {{
      margin: 0 auto; max-width: 1100px; padding: 24px 24px 80px;
      font: 16px/1.5 "Segoe UI", Helvetica, Arial, sans-serif; color: #1b1b1b;
    }}
    nav {{
      display: flex; flex-wrap: wrap; gap: 8px; position: sticky; top: 0;
      background: #fff; padding: 12px 0; border-bottom: 1px solid #e2e2e2; z-index: 1;
    }}
    nav a {{ color: #16537e; text-decoration: none; border: 1px solid #e2e2e2; padding: 4px 10px; }}
    h2.part {{ margin-top: 36px; border-top: 1px solid #e2e2e2; padding-top: 18px; }}
    pre {{
      white-space: pre-wrap; word-break: break-word; background: #f7f7f7;
      border: 1px solid #e2e2e2; padding: 12px; max-height: 70vh; overflow: auto;
      font: 12px/1.4 ui-monospace, SFMono-Regular, Menlo, Consolas, monospace;
    }}
    details {{ border: 1px solid #e2e2e2; padding: 8px 12px; margin: 12px 0; }}
    summary {{ cursor: pointer; font-weight: 600; }}
    summary span, .path {{ color: #5c5c5c; font-weight: 400; font-size: 13px; }}
    code {{ background: #f3f3f3; padding: 0.1rem 0.3rem; }}
    table {{ border-collapse: collapse; }}
    th, td {{ border-bottom: 1px solid #e2e2e2; }}
    /*EXTRA_CSS*/
  </style>
</head>
<body>
  <h1>SNN MNIST gem5 report</h1>
  <p>The baseline run and the L2 size sweep. Regenerated by <code>./profile.sh</code>.</p>
  <nav>{nav}</nav>
  {body}
</body>
</html>
"""
    return page.replace("/*EXTRA_CSS*/", "\n".join(extra_css))


def main() -> int:
    if len(sys.argv) != 2:
        print("Usage: gem5_full_report.py /path/to/profiles", file=sys.stderr)
        return 1
    profile_root = Path(sys.argv[1])
    profile_root.mkdir(parents=True, exist_ok=True)
    report = profile_root / "report.html"
    report.write_text(build(profile_root))
    print(report.as_posix())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
